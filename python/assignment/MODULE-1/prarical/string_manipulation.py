# string
text = "PythonProgramming"

# different slicing examples
print("Original String:", text)

print("First 6 characters:", text[:6])      # index 0 to 5
print("From index 6 onwards:", text[6:])    # index 6 to end
print("Middle part (2 to 10):", text[2:10]) # index 2 to 9
print("Every 2nd character:", text[::2])    # step = 2
print("Reverse string:", text[::-1])        # reverse           